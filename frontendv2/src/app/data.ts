function makeAI(category: string, dept: string, severity: number, duplicateOf?: string): AIAnalysis {
  const sentimentMap: Record<number, AIAnalysis['sentiment']> = {
    1: 'NEUTRAL', 2: 'NEUTRAL', 3: 'CONCERNED', 4: 'CONCERNED',
    5: 'CONCERNED', 6: 'URGENT', 7: 'URGENT', 8: 'DISTRESSED',
    9: 'DISTRESSED', 10: 'DISTRESSED',
  };
  const confidenceBase = [0.87, 0.91, 0.84, 0.93, 0.88, 0.79, 0.95, 0.82];
  const confIdx = category.length % confidenceBase.length;
  const spamBase = [0.01, 0.02, 0.03, 0.01, 0.02];
  const spamIdx = dept.length % spamBase.length;
  const urgency = Math.min(10, Math.max(1, severity + (category.length % 3) - 1));

  return {
    categoryConfidence: confidenceBase[confIdx],
    suggestedCategory: category,
    suggestedDepartment: dept,
    severity,
    urgency,
    isDuplicate: !!duplicateOf,
    duplicateOf,
    summary: `AI analysis: ${category} issue, severity ${severity}/10. Recommended routing to ${dept}.`,
    tags: [category.toLowerCase().replace(/\s/g, '-'), dept.toLowerCase().split(' ')[0], 'campus'],
    sentiment: sentimentMap[severity] || 'NEUTRAL',
    spamScore: spamBase[spamIdx],
    recommendation:
      severity >= 8
        ? 'Immediate escalation recommended. SLA breach risk: HIGH.'
        : severity >= 5
        ? 'Expedite standard processing. Monitor SLA timer.'
        : 'Route through standard workflow. No escalation required.',
    slaBreachRisk: severity >= 8 ? 'HIGH' : severity >= 5 ? 'MEDIUM' : 'LOW',
    modelVersion: 'ethos-analysis-v2.4',
    processedAt: subHours(now, (severity * 3 + category.length) % 48).toISOString(),
    explanation: {
      field: 'CATEGORY',
      explanation: `The report content was classified as ${category} based on recurring terminology and contextual indicators. The ${dept} department was identified as the most appropriate routing target based on historical case patterns.`,
      contributingTerms: [
        category.toLowerCase(),
        dept.split(' ')[0].toLowerCase(),
        'campus',
        ...(severity >= 7 ? ['urgent', 'immediate'] : []),
      ],
      modelVersion: 'ethos-analysis-v2.4',
    },
  };
}


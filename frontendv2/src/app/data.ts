function makeHash(): string {
  const chars = 'ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789';
  let result = '';
  const seeds = [1, 3, 7, 11, 13, 17, 19, 23];
  for (let i = 0; i < 8; i++) {
    result += chars[(seeds[i] * 7 + i * 3) % chars.length];
  }
  return result;
}


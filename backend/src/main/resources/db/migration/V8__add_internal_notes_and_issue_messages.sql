-- Phase 2.6: Internal Notes & Investigator Messaging

-- 1. Create issue_internal_notes table
CREATE TABLE IF NOT EXISTS issue_internal_notes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    issue_id BIGINT NOT NULL,
    author_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    content VARCHAR(5000) NOT NULL,
    CONSTRAINT fk_internal_notes_issue FOREIGN KEY (issue_id) REFERENCES issues(id) ON DELETE CASCADE,
    CONSTRAINT fk_internal_notes_author FOREIGN KEY (author_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_internal_notes_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_internal_notes_issue ON issue_internal_notes(issue_id);
CREATE INDEX IF NOT EXISTS idx_internal_notes_org ON issue_internal_notes(organization_id);
CREATE INDEX IF NOT EXISTS idx_internal_notes_issue_org ON issue_internal_notes(issue_id, organization_id, created_at);

-- 2. Create issue_messages table
CREATE TABLE IF NOT EXISTS issue_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    issue_id BIGINT NOT NULL,
    sender_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    content VARCHAR(5000) NOT NULL,
    CONSTRAINT fk_messages_issue FOREIGN KEY (issue_id) REFERENCES issues(id) ON DELETE CASCADE,
    CONSTRAINT fk_messages_sender FOREIGN KEY (sender_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT fk_messages_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_issue_messages_issue ON issue_messages(issue_id);
CREATE INDEX IF NOT EXISTS idx_issue_messages_org ON issue_messages(organization_id);
CREATE INDEX IF NOT EXISTS idx_issue_messages_issue_org ON issue_messages(issue_id, organization_id, created_at);

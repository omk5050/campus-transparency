-- Phase 2.8B: Secure Image Attachments using Cloudinary

CREATE TABLE IF NOT EXISTS issue_attachments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    issue_id BIGINT NOT NULL,
    organization_id BIGINT NOT NULL,
    uploaded_by BIGINT NOT NULL,
    original_filename VARCHAR(255) NOT NULL,
    cloudinary_public_id VARCHAR(255) NOT NULL,
    secure_url VARCHAR(1000) NOT NULL,
    resource_type VARCHAR(64) NOT NULL DEFAULT 'image',
    format VARCHAR(32),
    bytes BIGINT NOT NULL,
    width INTEGER,
    height INTEGER,
    CONSTRAINT fk_attachments_issue FOREIGN KEY (issue_id) REFERENCES issues(id) ON DELETE CASCADE,
    CONSTRAINT fk_attachments_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE,
    CONSTRAINT fk_attachments_uploader FOREIGN KEY (uploaded_by) REFERENCES users(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_attachments_issue ON issue_attachments(issue_id);
CREATE INDEX IF NOT EXISTS idx_attachments_org ON issue_attachments(organization_id);
CREATE INDEX IF NOT EXISTS idx_attachments_issue_org ON issue_attachments(issue_id, organization_id, created_at);
CREATE INDEX IF NOT EXISTS idx_attachments_cloudinary_id ON issue_attachments(cloudinary_public_id);

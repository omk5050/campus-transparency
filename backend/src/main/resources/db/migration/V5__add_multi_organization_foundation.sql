-- V5__add_multi_organization_foundation.sql
-- Phase 2.3: Multi-Organization Foundation

-- 1. Create organizations table
CREATE TABLE IF NOT EXISTS organizations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    name VARCHAR(200) NOT NULL,
    organization_type VARCHAR(50) NOT NULL,
    status VARCHAR(50) NOT NULL,
    official_email VARCHAR(255)
);

-- 2. Insert default active organization for existing data
INSERT INTO organizations (name, organization_type, status, official_email, created_at, updated_at)
SELECT 'ETHOS University Campus', 'UNIVERSITY', 'ACTIVE', 'admin@ethos-campus.edu', CURRENT_TIMESTAMP, CURRENT_TIMESTAMP
WHERE NOT EXISTS (
    SELECT 1 FROM organizations WHERE name = 'ETHOS University Campus'
);

-- 3. Add organization_id to users
ALTER TABLE users ADD COLUMN IF NOT EXISTS organization_id BIGINT;

-- Backfill existing users to default organization
UPDATE users
SET organization_id = (SELECT id FROM organizations WHERE name = 'ETHOS University Campus' LIMIT 1)
WHERE organization_id IS NULL;

-- Enforce foreign key on users (remains nullable for future platform-level Super Admin)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_users_organization'
    ) THEN
        ALTER TABLE users
        ADD CONSTRAINT fk_users_organization
        FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE RESTRICT;
    END IF;
END $$;

-- 4. Add organization_id to issues
ALTER TABLE issues ADD COLUMN IF NOT EXISTS organization_id BIGINT;

-- Backfill existing issues to default organization
UPDATE issues
SET organization_id = (SELECT id FROM organizations WHERE name = 'ETHOS University Campus' LIMIT 1)
WHERE organization_id IS NULL;

-- Make organization_id NOT NULL on issues
ALTER TABLE issues ALTER COLUMN organization_id SET NOT NULL;

-- Enforce foreign key on issues
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint WHERE conname = 'fk_issues_organization'
    ) THEN
        ALTER TABLE issues
        ADD CONSTRAINT fk_issues_organization
        FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE RESTRICT;
    END IF;
END $$;

-- 5. Indexes for multi-tenant queries and isolation
CREATE INDEX IF NOT EXISTS idx_organizations_status ON organizations(status);
CREATE INDEX IF NOT EXISTS idx_users_organization_id ON users(organization_id);
CREATE INDEX IF NOT EXISTS idx_issues_organization_id ON issues(organization_id);
CREATE INDEX IF NOT EXISTS idx_issues_org_status ON issues(organization_id, status);
CREATE INDEX IF NOT EXISTS idx_issues_org_tracking ON issues(organization_id, tracking_code);
CREATE INDEX IF NOT EXISTS idx_audit_logs_issue_id ON audit_logs(issue_id);

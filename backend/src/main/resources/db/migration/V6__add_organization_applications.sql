-- V6__add_organization_applications.sql
-- Phase 2.4: Organization Registration & Super Admin Approval

-- 1. Create organization_applications table
CREATE TABLE IF NOT EXISTS organization_applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    organization_name VARCHAR(200) NOT NULL,
    organization_type VARCHAR(50) NOT NULL,
    official_email VARCHAR(255) NOT NULL,
    contact_person VARCHAR(100) NOT NULL,
    address VARCHAR(500) NOT NULL,
    website VARCHAR(255),
    description VARCHAR(2000) NOT NULL,
    requested_admin_email VARCHAR(255) NOT NULL,
    requested_admin_username VARCHAR(100) NOT NULL,
    requested_admin_password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(50) NOT NULL,
    rejection_reason VARCHAR(1000),
    reviewed_by VARCHAR(100),
    reviewed_at TIMESTAMP(6) WITH TIME ZONE,
    approved_organization_id BIGINT,
    CONSTRAINT fk_org_apps_approved_org FOREIGN KEY (approved_organization_id) REFERENCES organizations(id) ON DELETE SET NULL
);

-- 2. Create organization_application_audit_logs table
CREATE TABLE IF NOT EXISTS organization_application_audit_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    application_id BIGINT NOT NULL,
    action VARCHAR(50) NOT NULL,
    performed_by VARCHAR(100),
    details VARCHAR(2000),
    CONSTRAINT fk_org_app_audit_app FOREIGN KEY (application_id) REFERENCES organization_applications(id) ON DELETE CASCADE
);

-- 3. Indexes for query performance and integrity
CREATE INDEX IF NOT EXISTS idx_org_apps_status ON organization_applications(status);
CREATE INDEX IF NOT EXISTS idx_org_apps_org_name ON organization_applications(organization_name);
CREATE INDEX IF NOT EXISTS idx_org_apps_official_email ON organization_applications(official_email);
CREATE INDEX IF NOT EXISTS idx_org_apps_admin_username ON organization_applications(requested_admin_username);
CREATE INDEX IF NOT EXISTS idx_org_app_audit_app_id ON organization_application_audit_logs(application_id);

-- Phase 2.5: Organization Join Codes for Student/Staff Onboarding

CREATE TABLE IF NOT EXISTS organization_join_codes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    created_at TIMESTAMP(6) WITH TIME ZONE,
    updated_at TIMESTAMP(6) WITH TIME ZONE,
    code VARCHAR(64) NOT NULL UNIQUE,
    organization_id BIGINT NOT NULL,
    target_role VARCHAR(20) NOT NULL,
    created_by VARCHAR(100) NOT NULL,
    max_uses INT,
    used_count INT NOT NULL DEFAULT 0,
    expires_at TIMESTAMP(6) WITH TIME ZONE,
    revoked BOOLEAN NOT NULL DEFAULT FALSE,
    revoked_at TIMESTAMP(6) WITH TIME ZONE,
    revoked_by VARCHAR(100),
    CONSTRAINT fk_join_codes_org FOREIGN KEY (organization_id) REFERENCES organizations(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_join_codes_code ON organization_join_codes(code);
CREATE INDEX IF NOT EXISTS idx_join_codes_org_id ON organization_join_codes(organization_id);
CREATE INDEX IF NOT EXISTS idx_join_codes_active ON organization_join_codes(revoked, expires_at);
